    /// The audit's failure scenario: `/steer be brief` mid-stream used to
    /// render "⏩ Steer queued for the active turn: be briefOK, keeping it
    /// short."
    @Test @MainActor func steerStatusLineIsItsOwnBubble() throws {
        let vm = Self.engagedVM()
        vm.handleACPEvent(try #require(Self.parse(Self.streamedChunk)))
        vm.addUserMessage(text: "/steer be brief")
        vm.handleACPEvent(try #require(Self.parse(Self.steerStatus)))
