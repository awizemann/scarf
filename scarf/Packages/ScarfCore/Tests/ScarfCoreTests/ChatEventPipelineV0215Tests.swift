/// R09 of the Hermes v0.21.5 audit remediation — the chat event pipeline.
///
///  - S02-F2: live tool cards for built-in tools. Hermes sends `rawInput`
///    only for unknown/plugin tools; the target lives in `title` and
///    `locations` (`acp_adapter/tools.py:797-815` @ v2026.9.24).
///  - S02-F4: `messageId` segments replies, so an id-less mid-turn status
///    line is not glued to the resumed turn's text.
///  - S02-F1: a local user echo is reconciled with state.db by the WIRE
///    text and its send position, never by the typed text.
///
/// Wire fixtures are the exact JSON Hermes v2026.9.24 emits: generated by
/// running `acp_adapter.tools.build_tool_start` / `acp.update_agent_message_text`
/// from the tagged tree's own venv and dumping with `by_alias=True,
/// exclude_none=True`. Stored-row strings come from the same tree
/// (`_durable_content`, `steer_user_row`, `_attach_interrupted_prompt`).
@Suite struct ChatEventPipelineV0215Tests {

    // MARK: - Helpers

    private static func parse(_ updateJSON: String) -> ACPEvent? {
        let json = #"{"jsonrpc":"2.0","method":"session/update","params":"# + updateJSON + "}"
        guard let raw = try? JSONDecoder().decode(ACPRawMessage.self, from: Data(json.utf8)) else {
            Issue.record("failed to decode ACPRawMessage fixture")
            return nil
        }
        return ACPEventParser.parse(notification: raw)
    }

    private static func toolStart(_ updateJSON: String) -> ACPToolCallEvent? {
        guard case .toolCallStart(_, let call)? = parse(updateJSON) else {
            Issue.record("expected .toolCallStart")
            return nil
        }
        return call
    }

    // Exact `tool_call` / `tool_call_update` notifications (params only).
    private static let readA = #"{"sessionId": "s", "update": {"kind": "read", "locations": [{"path": "Sources/a.swift"}], "title": "read_file: a.swift", "toolCallId": "tc-aaaaaaaaaaaa", "sessionUpdate": "tool_call"}}"#
    private static let readB = #"{"sessionId": "s", "update": {"kind": "read", "locations": [{"path": "Sources/b.swift"}], "title": "read_file: b.swift", "toolCallId": "tc-bbbbbbbbbbbb", "sessionUpdate": "tool_call"}}"#
    private static let terminal = #"{"sessionId": "s", "update": {"content": [{"content": {"text": "$ swift test --filter Foo", "type": "text"}, "type": "content"}], "kind": "execute", "locations": [], "title": "terminal: swift test --filter Foo", "toolCallId": "tc-cccccccccccc", "sessionUpdate": "tool_call"}}"#
    private static let plugin = #"{"sessionId": "s", "update": {"content": [{"content": {"text": "{\n  \"q\": \"x\"\n}", "type": "text"}, "type": "content"}], "kind": "other", "locations": [], "rawInput": {"q": "x"}, "title": "my_plugin_tool", "toolCallId": "tc-dddddddddddd", "sessionUpdate": "tool_call"}}"#

    private static func complete(_ id: String) -> String {
        #"{"sessionId": "s", "update": {"content": [{"content": {"text": "Read file\n\n```\nhi\n```", "type": "text"}, "type": "content"}], "kind": "read", "status": "completed", "toolCallId": ""# + id + #"", "sessionUpdate": "tool_call_update"}}"#
    }

    @MainActor
    private static func engagedVM() -> RichChatViewModel {
        let vm = RichChatViewModel(context: .local)
        vm.setSessionId("s")
        vm.addUserMessage(text: "go")
        return vm
    }

    @MainActor
    private static func liveSegment(_ vm: RichChatViewModel) -> MessageGroup.ChatActivitySegment? {
        for group in vm.messageGroups.reversed() {
            for item in group.transcriptItems(coalesceText: true).reversed() {
                if case .activity(let seg) = item { return seg }
            }
        }
        return nil
    }

    // MARK: - S02-F2 parser

    @Test func builtInToolStartCarriesLocationButNoArguments() throws {
        let call = try #require(Self.toolStart(Self.readA))
        #expect(call.rawInput == nil)
        #expect(call.argumentsJSON == "{}")
        #expect(call.functionName == "read_file")
        #expect(call.locationPaths == ["Sources/a.swift"])
        // The full path beats the title's basename preview.
        #expect(call.livePreview == "Sources/a.swift")
    }

    @Test func terminalStartFallsBackToTheTitlePreview() throws {
        let call = try #require(Self.toolStart(Self.terminal))
        #expect(call.locationPaths.isEmpty)
        #expect(call.livePreview == "swift test --filter Foo")
    }

    @Test func pluginToolStillCarriesRawInput() throws {
        let call = try #require(Self.toolStart(Self.plugin))
        #expect(call.rawInput?["q"] as? String == "x")
        // Bare-name title, no location → nothing to preview.
        #expect(call.livePreview == nil)
    }

    // MARK: - S02-F2 live transcript

    /// The audit's failure scenario: three reads of different files used to
    /// collapse into one "read_file ×3" card with no path.
    @Test @MainActor func consecutiveReadsOfDifferentFilesStaySeparateCards() throws {
        let vm = Self.engagedVM()
        let readC = Self.readB
            .replacingOccurrences(of: "b.swift", with: "c.swift")
            .replacingOccurrences(of: "tc-bbbbbbbbbbbb", with: "tc-eeeeeeeeeeee")
        for (start, id) in [(Self.readA, "tc-aaaaaaaaaaaa"), (Self.readB, "tc-bbbbbbbbbbbb"), (readC, "tc-eeeeeeeeeeee")] {
            vm.handleACPEvent(try #require(Self.parse(start)))
            vm.handleACPEvent(try #require(Self.parse(Self.complete(id))))
        }
        let seg = try #require(Self.liveSegment(vm))
        #expect(seg.totalToolCount == 3)
        #expect(seg.entries.count == 3)
        #expect(seg.entries.map(\.count) == [1, 1, 1])
        #expect(seg.entries.map(\.call.argumentsSummary) == ["Sources/a.swift", "Sources/b.swift", "Sources/c.swift"])
        // Inspector input: still the honest "{}" for arguments, with the
        // preview carried alongside.
        #expect(seg.entries.allSatisfy { $0.call.hasNoArguments })
    }

    /// Genuine repeats (same tool, same target) still collapse.
    @Test @MainActor func repeatedReadOfTheSameFileStillCollapses() throws {
        let vm = Self.engagedVM()
        let again = Self.readA.replacingOccurrences(of: "tc-aaaaaaaaaaaa", with: "tc-ffffffffffff")
        vm.handleACPEvent(try #require(Self.parse(Self.readA)))
        vm.handleACPEvent(try #require(Self.parse(Self.complete("tc-aaaaaaaaaaaa"))))
        vm.handleACPEvent(try #require(Self.parse(again)))
        vm.handleACPEvent(try #require(Self.parse(Self.complete("tc-ffffffffffff"))))
        let seg = try #require(Self.liveSegment(vm))
        #expect(seg.entries.count == 1)
        #expect(seg.entries.first?.count == 2)
    }

    /// A call reloaded from state.db has real arguments and no preview; the
    /// summary still comes from the arguments.
    @Test func storedCallSummaryIgnoresMissingPreview() {
        let stored = HermesToolCall(callId: "c1", functionName: "read_file", arguments: #"{"path":"Sources/a.swift"}"#)
        #expect(stored.livePreview == nil)
        #expect(stored.argumentsSummary == "Sources/a.swift")
        let live = HermesToolCall(callId: "c2", functionName: "read_file", arguments: "{}", livePreview: "Sources/a.swift")
        #expect(live.argumentsSummary == "Sources/a.swift")
        let bare = HermesToolCall(callId: "c3", functionName: "todo", arguments: "{}")
        #expect(bare.argumentsSummary == "")
    }

    // MARK: - S02-F4 messageId

    private static let streamedChunk = #"{"sessionId": "s", "update": {"content": {"text": "Working on it", "type": "text"}, "messageId": "3f1c2a9e-8b7d-4c6e-9a51-2d0f4b7e6c13", "sessionUpdate": "agent_message_chunk"}}"#
    private static let steerStatus = #"{"sessionId": "s", "update": {"content": {"text": "⏩ Steer queued for the active turn: be brief", "type": "text"}, "sessionUpdate": "agent_message_chunk"}}"#
    private static let resumedChunk = #"{"sessionId": "s", "update": {"content": {"text": "OK, keeping it short.", "type": "text"}, "messageId": "3f1c2a9e-8b7d-4c6e-9a51-2d0f4b7e6c13", "sessionUpdate": "agent_message_chunk"}}"#
    private static let thought = #"{"sessionId": "s", "update": {"content": {"text": "thinking", "type": "text"}, "messageId": "3f1c2a9e-8b7d-4c6e-9a51-2d0f4b7e6c13", "sessionUpdate": "agent_thought_chunk"}}"#

    @Test func chunkParsingCarriesMessageId() {
        guard case .messageChunk(_, _, _, _, let id)? = Self.parse(Self.streamedChunk) else {
            Issue.record("expected .messageChunk"); return
