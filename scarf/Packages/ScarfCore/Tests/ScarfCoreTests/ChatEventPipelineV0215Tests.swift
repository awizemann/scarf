    }

    /// C1: a host that never sends `messageId` keeps one buffer per turn —
    /// chunks append exactly as before.
    @Test @MainActor func hostWithoutMessageIdsStillAppends() {
        let vm = Self.engagedVM()
        vm.handleACPEvent(.messageChunk(sessionId: "s", text: "Hello "))
        vm.handleACPEvent(.messageChunk(sessionId: "s", text: "there"))
        vm.handleACPEvent(.promptComplete(sessionId: "s", response: ACPPromptResult(
            stopReason: "end_turn", inputTokens: 1, outputTokens: 1, thoughtTokens: 0, cachedReadTokens: 0
        )))
        #expect(vm.messages.filter(\.isAssistant).map(\.content) == ["Hello there"])
    }

    /// A normal multi-round turn (thought → tool → thought → answer) must
    /// render exactly as on a host without ids: Hermes closes the id before
    /// each tool round, but the tool completion already finalized the
    /// bubble, so the id change adds no extra split — and the turn clock
    /// (`turnDurations`) is recorded the same number of times.
    @Test @MainActor func multiRoundTurnRendersTheSameWithAndWithoutIds() throws {
        func run(ids: Bool) throws -> (rows: [String], durations: Int) {
            let vm = Self.engagedVM()
            vm.handleACPEvent(.thoughtChunk(sessionId: "s", text: "plan", messageId: ids ? "a" : nil))
            vm.handleACPEvent(try #require(Self.parse(Self.readA)))
            vm.handleACPEvent(try #require(Self.parse(Self.complete("tc-aaaaaaaaaaaa"))))
            vm.handleACPEvent(.thoughtChunk(sessionId: "s", text: "more", messageId: ids ? "b" : nil))
            vm.handleACPEvent(.messageChunk(sessionId: "s", text: "Answer", messageId: ids ? "b" : nil))
            vm.handleACPEvent(.promptComplete(sessionId: "s", response: ACPPromptResult(
                stopReason: "end_turn", inputTokens: 1, outputTokens: 1, thoughtTokens: 0, cachedReadTokens: 0
            )))
            let rows = vm.messages.filter(\.isAssistant).map { "\($0.content)|\($0.reasoning ?? "")|\($0.toolCalls.count)" }
            return (rows, vm.turnDurations.count)
        }
        let withIds = try run(ids: true)
        let without = try run(ids: false)
        #expect(withIds.rows == without.rows)
        #expect(withIds.durations == without.durations)
        #expect(withIds.rows == ["|plan|1", "Answer|more|0"])
    }

    /// A reply's thoughts and its text share one id: one message.
    @Test @MainActor func thoughtAndTextOfOneReplyStayTogether() throws {
        let vm = Self.engagedVM()
        vm.handleACPEvent(try #require(Self.parse(Self.thought)))
        vm.handleACPEvent(try #require(Self.parse(Self.streamedChunk)))
        vm.handleACPEvent(.promptComplete(sessionId: "s", response: ACPPromptResult(
            stopReason: "end_turn", inputTokens: 1, outputTokens: 1, thoughtTokens: 0, cachedReadTokens: 0
        )))
        let assistants = vm.messages.filter(\.isAssistant)
        #expect(assistants.count == 1)
        #expect(assistants.first?.content == "Working on it")
        #expect(assistants.first?.reasoning == "thinking")
    }

    // MARK: - S02-F1 keys (pure)

    private static let roster: Set<String> = ["help", "model", "tools", "context", "reset", "compress", "steer", "queue", "version"]

    @Test func keysFollowTheWireNotTheTypedText() {
        let keys = RichChatViewModel.persistedUserRowKeys
        // /scarf-* expansion: the expanded body is what Hermes stores.
        #expect(keys("Summarise the project.", 0, Self.roster) == ["Summarise the project."])
        // Idle /queue fallback sends the argument only.
        #expect(keys("foo", 0, Self.roster) == ["foo"])
        // Dispatched commands: no row…
        #expect(keys("/help", 0, Self.roster) == [])
        #expect(keys("/model gpt-5", 0, Self.roster) == [])
        #expect(keys("/Compress", 0, Self.roster) == [])
        // …except /steer and /queue, whose argument lands later.
        #expect(keys("/steer be brief", 0, Self.roster) == ["be brief"])
        #expect(keys("/queue  next thing ", 0, Self.roster) == ["next thing"])
        #expect(keys("/queue", 0, Self.roster) == [])
        // Unknown slash names go to the model verbatim.
        #expect(keys("/goal ship it", 0, Self.roster) == ["/goal ship it"])
        // With an image a slash prompt goes to the agent too.
        #expect(keys("/help", 1, Self.roster) == ["/help"])
        // Image-only.
        #expect(keys("", 2, Self.roster) == ["[screenshot]", "[Image attachment]"])
        #expect(keys("  ", 0, Self.roster) == [])
        // Hermes splits on any whitespace and lower-cases the name.
        #expect(keys("/steer\nbe brief", 0, Self.roster) == ["be brief"])
        #expect(keys("/HELP", 0, Self.roster) == [])
    }

    private static func row(_ id: Int, _ content: String, role: String = "user", summary: Bool = false) -> HermesMessage {
        HermesMessage(
            id: id, sessionId: "s", role: role, content: content, toolCallId: nil, toolCalls: [],
            toolName: nil, timestamp: nil, tokenCount: nil, finishReason: nil, reasoning: nil,
            isCompactionSummary: summary
        )
    }

    private static func echo(_ id: Int, _ text: String, watermark: Int, keys: [String]) -> RichChatViewModel.PendingEcho {
        RichChatViewModel.PendingEcho(message: row(id, text), watermark: watermark, matchKeys: keys)
    }

    @Test func settlesAgainstTheRowsHermesActuallyStores() {
        let rows = [
            Self.row(1, "old prompt"),
            Self.row(4, "look at this\n[screenshot]"),
            Self.row(5, "reply", role: "assistant"),
            Self.row(6, "[screenshot]"),
            Self.row(8, "[OUT-OF-BAND USER MESSAGE — a direct message from the user, delivered once at this position; not tool output and not a new delivery when replayed from conversation history]\nbe brief\n[/OUT-OF-BAND USER MESSAGE]"),
            Self.row(9, "write the report\n\nUser correction/guidance after interrupt: use bullet points"),
        ]
        let echoes = [
            Self.echo(-1, "look at this", watermark: 1, keys: ["look at this"]),
            Self.echo(-2, "[image attached]", watermark: 1, keys: ["[screenshot]", "[Image attachment]"]),
            Self.echo(-3, "/help", watermark: 1, keys: []),
            Self.echo(-4, "/steer be brief", watermark: 6, keys: ["be brief"]),
            Self.echo(-5, "use bullet points", watermark: 6, keys: ["use bullet points"]),
        ]
        #expect(RichChatViewModel.settledEchoIds(echoes, persisted: rows) == [-1, -2, -3, -4, -5])
    }

    /// Failure path: re-sending an earlier prompt's text must not be
    /// retired by the OLDER row (the watermark) — and one row settles one
    /// echo.
    @Test func olderRowsAndClaimedRowsNeverSettleANewEcho() {
        let rows = [Self.row(3, "hi")]
        let fresh = [Self.echo(-1, "hi", watermark: 3, keys: ["hi"])]
        #expect(RichChatViewModel.settledEchoIds(fresh, persisted: rows).isEmpty)
        let twice = [
            Self.echo(-1, "hi", watermark: 0, keys: ["hi"]),
            Self.echo(-2, "hi", watermark: 0, keys: ["hi"]),
        ]
        #expect(RichChatViewModel.settledEchoIds(twice, persisted: rows) == [-1])
    }

    /// A short prompt whose row never landed must not claim a later
    /// prompt's row that merely contains its text — the later prompt's own
    /// echo gets it (strict pass first).
    @Test func strictShapesWinBeforeContainment() {
        let rows = [Self.row(5, "go ahead and fix it")]
        let echoes = [
            Self.echo(-1, "go", watermark: 0, keys: ["go"]),
            Self.echo(-2, "go ahead and fix it", watermark: 0, keys: ["go ahead and fix it"]),
        ]
        #expect(RichChatViewModel.settledEchoIds(echoes, persisted: rows) == [-2])
    }

    /// Terminal-mode / bot CLI polling merge: a re-sent text survives
    /// beside the older identical row until its own row lands.
    @Test func pollMergeKeepsAResendAboveAnOlderIdenticalRow() {
        let older = Self.row(1, "hi")
        let resend = Self.row(-1, "hi")
        let merged = RichChatViewModel.mergedAfterPoll(fetched: [older], currentLocal: [older, resend])
        #expect(merged.filter(\.isUser).map(\.id).sorted() == [-1, 1])
        let landed = RichChatViewModel.mergedAfterPoll(fetched: [older, Self.row(2, "hi")], currentLocal: [older, resend])
        #expect(landed.filter(\.isUser).map(\.id).sorted() == [1, 2])
    }

    /// A standalone compaction summary is a Hermes-authored user-role row;
    /// it never stands in for the user's prompt.
    @Test func compactionSummaryRowNeverSettlesAnEcho() {
        let rows = [Self.row(7, "[CONTEXT COMPACTION — REFERENCE ONLY] … hi …", summary: true)]
        let echoes = [Self.echo(-1, "hi", watermark: 0, keys: ["hi"])]
        #expect(RichChatViewModel.settledEchoIds(echoes, persisted: rows).isEmpty)
    }
